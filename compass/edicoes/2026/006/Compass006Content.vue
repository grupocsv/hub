<h2>1. A Força Demográfica: O Envelhecimento como Motor Inelástico de Demanda</h2>
<p>A oftalmologia é uma das especialidades médicas mais sensíveis à estrutura etária da população. Ao contrário de outras áreas onde a demanda pode ser modulada por fatores comportamentais ou epidemiológicos transitórios, a prevalência de doenças oculares graves — como catarata, glaucoma e Degeneração Macular Relacionada à Idade (DMRI) — apresenta correlação quase perfeita com o avanço da idade.</p>
<p>O Brasil atravessa uma transição demográfica acelerada. Dados do IBGE [2] revelam que a proporção de idosos (65 anos ou mais) na população dobrou em pouco mais de duas décadas, saltando de 5,84% no Censo de 2000 para 10,92% no Censo de 2022. O índice de envelhecimento, que mede a proporção de idosos para cada 100 crianças de 0 a 14 anos, subiu de 30,8 em 2010 para 55,2 em 2022.</p>
<p>Na saúde suplementar, que concentra aproximadamente 51 milhões de beneficiários, essa transição é ainda mais pronunciada. A carteira de idosos nas operadoras cresce a taxas superiores à média populacional, pressionando a utilização de serviços oftalmológicos. A catarata, por exemplo, afeta mais de 70% das pessoas acima de 70 anos. O tratamento definitivo é invariavelmente cirúrgico. Não se trata de uma demanda que pode ser evitada por programas de prevenção primária; é uma demanda inelástica que se acumula no topo da pirâmide etária.</p>

<h3>1.1. O Impacto Financeiro da Demanda Inelástica</h3>
