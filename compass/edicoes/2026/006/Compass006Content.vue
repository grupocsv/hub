<section class="compass-section">
<h2>2. A Reação das Operadoras: Do <em>Fee for Service</em> aos Modelos Baseados em Valor</h2>
<p>A resposta imediata das operadoras à pressão de custos oftalmológicos foi a intensificação das ferramentas tradicionais de controle: glosas, restrição de rede e auditorias rigorosas. No entanto, essas medidas atuam apenas sobre a frequência (tentando coibir procedimentos desnecessários), mas falham em controlar a severidade (o custo de cada procedimento realizado), especialmente quando o modelo de remuneração subjacente permanece o <em>fee for service</em>.</p>
<p>A reorganização do mercado oftalmológico passa necessariamente pela transição para modelos de remuneração que alinhem os incentivos entre pagadores e prestadores. Três movimentos principais se destacam:</p>

<h3>2.1. Pacotização de Procedimentos Cirúrgicos</h3>
<p>A cirurgia de catarata, por seu alto volume e previsibilidade clínica, é o candidato ideal para a pacotização. No modelo de pacote, a operadora remunera o prestador com um valor fixo que engloba honorários médicos, taxas de sala, medicamentos e, crucialmente, a lente intraocular (OPME). Essa transferência de risco obriga o prestador a buscar eficiência operacional e a padronizar insumos. Como demonstrado na edição 005 do Compass™, a padronização de OPME é responsável por até 66% do saving estrutural em pacotes cirúrgicos.</p>

<h3>2.2. Verticalização e Redes Referenciadas</h3>
<p>Para obter controle total sobre a jornada do paciente e os custos associados, algumas operadoras optam pela verticalização, construindo clínicas e centros cirúrgicos oftalmológicos próprios. Quando a verticalização não é viável, a estratégia é o estabelecimento de redes referenciadas estreitas: a operadora direciona o volume de pacientes para um número reduzido de prestadores de alta eficiência em troca de tabelas de remuneração mais vantajosas (pacotes ou <em>capitation</em>).</p>

<h3>2.3. Gestão Populacional (<em>Capitation</em>)</h3>
<p>Embora ainda incipiente na oftalmologia brasileira, o modelo de <em>capitation</em> — onde o prestador recebe um valor fixo mensal por beneficiário para cobrir todas as necessidades oftalmológicas de uma população definida — representa o estágio mais avançado de alinhamento de incentivos. Nesse modelo, o prestador lucra ao manter a população saudável e ao resolver os problemas de forma resolutiva e eficiente, evitando o sobretratamento inerente ao <em>fee for service</em>.</p>
</section>

<section class="compass-section">
<h2>3. A Reorganização dos Prestadores: Escala, Eficiência e Consolidação</h2>
<p>Do lado dos prestadores (clínicas e hospitais oftalmológicos), a transição demográfica e a pressão das operadoras por modelos de pacotes exigem uma reestruturação profunda do modelo de negócios. A clínica oftalmológica tradicional, fragmentada e ineficiente, não sobrevive em um ambiente de margens comprimidas.</p>

<h3>3.1. A Busca por Escala e a Onda de Consolidação</h3>
<p>O mercado oftalmológico brasileiro é altamente fragmentado, composto por milhares de clínicas de pequeno e médio porte. No entanto, a necessidade de investir em tecnologia de ponta (equipamentos a laser caros) e de ganhar poder de barganha junto a fornecedores de OPME e operadoras tem impulsionado uma forte onda de consolidação. Fundos de <em>private equity</em> e grandes grupos de saúde têm adquirido e integrado clínicas, formando redes nacionais.</p>
<p>A escala permite:</p>
<ul>
<li><strong>Diluição de custos fixos:</strong> O custo de um equipamento de última geração é diluído por um volume muito maior de procedimentos.</li>
<li><strong>Poder de negociação com fornecedores:</strong> Redes consolidadas negociam compras diretas de lentes intraoculares e medicamentos com os fabricantes, eliminando intermediários e reduzindo o custo do OPME, o que é fundamental para a rentabilidade em modelos de pacotes.</li>
<li><strong>Poder de negociação com operadoras:</strong> Grandes redes têm capilaridade e volume para negociar contratos baseados em valor ou pacotes com operadoras de âmbito nacional.</li>
</ul>

<h3>3.2. Eficiência Operacional como Diferencial Competitivo</h3>
<p>Em um modelo de pacote, onde a receita é fixa, a margem de lucro é determinada exclusivamente pelo custo de produção. A eficiência operacional do centro cirúrgico oftalmológico torna-se a principal alavanca de resultado. Isso implica maximizar o giro de sala (número de cirurgias por hora), minimizar o tempo de <em>setup</em> entre procedimentos e padronizar rigorosamente os insumos utilizados.</p>
<p>Clínicas oftalmológicas de alta performance operam como verdadeiras "fábricas de cirurgias", onde cada etapa da jornada do paciente é mapeada e otimizada para garantir o menor custo unitário sem comprometer a qualidade clínica.</p>
</section>

<section class="compass-section">
<h2>4. Conclusão</h2>
<p>A oftalmologia na saúde suplementar brasileira não é mais apenas uma especialidade médica; é um mercado de R$ 10 bilhões em profunda reestruturação. A transição demográfica garante que a demanda por serviços oftalmológicos continuará crescendo de forma inelástica nas próximas décadas. Para as operadoras, a sobrevivência financeira exige a superação do <em>fee for service</em> e a adoção de modelos que transfiram o risco de severidade para os prestadores. Para os prestadores, a consolidação, a escala e a eficiência operacional extrema são os únicos caminhos para manter a lucratividade em um cenário de pacotização e margens comprimidas.</p>
</section>

